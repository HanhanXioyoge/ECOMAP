%% Figure 6: Flux comparison of Basic, Isozyme and Integrated ecModels
%
% Workflow
% --------
% 1. Load and calibrate Basic / Isozyme / Integrated models
% 2. Determine maximum growth for each model
% 3. Use Basic maximum growth as common growth state
% 4. Minimize protein requirement + pFBA
% 5. Collapse:
%       _EXP_n  -> parent reaction
%       _REV    -> reverse contribution to parent net flux
% 6. Align common parent reactions
% 7. Retain reactions carrying flux in all three models
% 8. Plot absolute net flux on log scale
% 9. Highlight off-diagonal reactions in both 3D and 2D
% 10. Export flux and correlation tables

