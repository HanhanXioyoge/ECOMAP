        ...
        'XTickLabel', tickLabels, ...
        'YTickLabel', tickLabels, ...
        ...
        'TickLabelInterpreter', 'tex', ...
        ...
        'FontName', FONT_NAME, ...
        'FontSize', FONT_SIZE, ...
        ...
        'LineWidth', AX_LINE_W, ...
        'TickDir', 'out', ...
        ...
        'Box', 'off', ...
        ...
        'XColor', 'k', ...
        'YColor', 'k', ...
        ...
        'GridColor', COLOR_GRID, ...
        'GridAlpha', 0.50, ...
        'GridLineStyle', '-', ...
        ...
        'XGrid', 'on', ...
        'YGrid', 'on', ...
        ...
        'XMinorGrid', 'off', ...
        'YMinorGrid', 'off');


    limits = 10.^[ ...
        minExp ...
        maxExp];


    xlim(ax, limits);

    ylim(ax, limits);


    axis( ...
        ax, ...
        'square');


    xlabel( ...
        ax, ...
        [xName ' flux magnitude'], ...
        ...
        'FontName', FONT_NAME, ...
        'FontSize', FONT_SIZE + 1);


    ylabel( ...
        ax, ...
        [yName ' flux magnitude'], ...
        ...
        'FontName', FONT_NAME, ...
        'FontSize', FONT_SIZE + 1);


    %% --------------------------------------------------------------------
    % Correlation in log10 space
    % ---------------------------------------------------------------------

    lx = log10(x);

    ly = log10(y);


    P = corrcoef( ...
        lx, ...
        ly);


    if numel(P) == 4

        pearson_r = P(1,2);

    else

        pearson_r = NaN;

    end


    if numel(lx) > 1

        spearman_rho = corr( ...
            lx, ...
            ly, ...
            ...
            'Type', ...
            'Spearman');

    else

        spearman_rho = NaN;

    end


    R2 = pearson_r^2;

    n = numel(x);


    %% --------------------------------------------------------------------
    % Pairwise fold difference
    % ---------------------------------------------------------------------

    foldDifference = max( ...
        y ./ x, ...
        x ./ y);


    idxAll = find( ...
        foldDifference >= foldThreshold);


    % Strongest deviations first
    [~, order] = sort( ...
        foldDifference(idxAll), ...
        'descend');


    idxAll = idxAll(order);


    idxLabel = idxAll( ...
        1:min( ...
            maxLabels, ...
            numel(idxAll)));


    %% --------------------------------------------------------------------
    % Highlight all off-diagonal reactions
    % ---------------------------------------------------------------------

    if ~isempty(idxAll)

        scatter( ...
            ax, ...
            ...
            x(idxAll), ...
            y(idxAll), ...
            ...
            HILITE_SZ, ...
            ...
            'o', ...
            ...
            'MarkerEdgeColor', COLOR_OUTLIER, ...
            'MarkerFaceColor', 'w', ...
            ...
            'LineWidth', 1.0);

    end


    %% --------------------------------------------------------------------
    % Annotate strongest parent reactions
    % ---------------------------------------------------------------------

    if ~isempty(idxLabel)

        for k = 1:numel(idxLabel)

            idx = idxLabel(k);


            if mod(k,2) == 1

                fx = 1.12;
                fy = 1.12;

            else

                fx = 1.12;
                fy = 0.88;

            end


            text( ...
                ax, ...
                ...
                x(idx) * fx, ...
                y(idx) * fy, ...
                ...
                rxnIDs(idx), ...
                ...
                'FontName', FONT_NAME, ...
                'FontSize', FONT_SIZE - 1, ...
                ...
                'Interpreter', 'none', ...
                ...
                'Color', COLOR_OUTLIER, ...
                ...
                'HorizontalAlignment', 'left', ...
                'VerticalAlignment', 'middle');

        end

    end


    %% --------------------------------------------------------------------
    % Panel label
    % ---------------------------------------------------------------------

    text( ...
        ax, ...
        ...
        -0.13, ...
        1.07, ...
        ...
        panelLabel, ...
        ...
        'Units', 'normalized', ...
        ...
        'FontName', FONT_NAME, ...
        'FontSize', FONT_SIZE + 3, ...
        'FontWeight', 'bold', ...
        ...
        'HorizontalAlignment', 'left', ...
        'VerticalAlignment', 'bottom', ...
        ...
        'Color', 'k');


    %% --------------------------------------------------------------------
    % Statistics
    % ---------------------------------------------------------------------

    statsText = { ...
        sprintf('r = %.3f', pearson_r)
        sprintf('R^2 = %.3f', R2)
        sprintf('\\rho = %.3f', spearman_rho)
        sprintf('n = %d', n)
        };


    text( ...
        ax, ...
        ...
        0.05, ...
        0.95, ...
        ...
        statsText, ...
        ...
        'Units', 'normalized', ...
        ...
        'FontName', FONT_NAME, ...
        'FontSize', FONT_SIZE, ...
        ...
        'VerticalAlignment', 'top', ...
        'HorizontalAlignment', 'left', ...
        ...
        'Interpreter', 'tex', ...
        ...
        'Color', 'k');


    %% --------------------------------------------------------------------
    % Return statistics
    % ---------------------------------------------------------------------

    stats = struct();


    stats.pearson_r = pearson_r;

    stats.R2 = R2;

    stats.spearman_rho = spearman_rho;

    stats.n = n;

    stats.nDeviating = numel(idxAll);

end