%% ========================================================================
% LOCAL FUNCTION 1
% Restore parent reaction net flux
% ========================================================================

function T = aggregateEcFlux(model, flux)

    rxns = string( ...
        model.rxns(:));

    flux = flux(:);


    %% --------------------------------------------------------------------
    % Remove protein bookkeeping reactions
    % ---------------------------------------------------------------------

    keep = ...
        ~startsWith(rxns, "usage_prot_") & ...
        ~startsWith(rxns, "draw_prot_") & ...
        rxns ~= "prot_pool_exchange";


    rxns = rxns(keep);

    flux = flux(keep);


    %% --------------------------------------------------------------------
    % Remove isozyme expansion suffix
    %
    % r_1138_EXP_1
    %       ->
    % r_1138
    %
    % r_1138_REV_EXP_2
    %       ->
    % r_1138_REV
    % ---------------------------------------------------------------------

    baseRxns = regexprep( ...
        rxns, ...
        '_EXP_[0-9]+$', ...
        '');


    %% --------------------------------------------------------------------
    % Detect irreversible reverse copies
    % ---------------------------------------------------------------------

    isReverse = endsWith( ...
        baseRxns, ...
        "_REV");


    %% --------------------------------------------------------------------
    % Reverse reaction contributes negatively to parent reaction
    % ---------------------------------------------------------------------

    signedFlux = flux;


    signedFlux(isReverse) = ...
        -signedFlux(isReverse);


    %% --------------------------------------------------------------------
    % Remove _REV
    %
    % r_1138_REV -> r_1138
    % ---------------------------------------------------------------------

    baseRxns = regexprep( ...
        baseRxns, ...
        '_REV$', ...
        '');


    %% --------------------------------------------------------------------
    % Remove possible bookkeeping prefix
    %
    % 001_r_1138 -> r_1138
    % ---------------------------------------------------------------------

    baseRxns = regexprep( ...
        baseRxns, ...
        '^[0-9]{3}_', ...
        '');


    %% --------------------------------------------------------------------
    % Aggregate all copies to parent reaction
    % ---------------------------------------------------------------------

    [uniqueRxns, ~, group] = unique( ...
        baseRxns, ...
        'stable');


    netFlux = accumarray( ...
        group, ...
        signedFlux, ...
        [], ...
        @sum);


    %% --------------------------------------------------------------------
    % Output
    % ---------------------------------------------------------------------

    T = table( ...
        uniqueRxns, ...
        netFlux, ...
        ...
        'VariableNames', { ...
            'ReactionID', ...
            'NetFlux'});

end


